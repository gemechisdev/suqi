    /** Returns list of any empty translation fields across all 3 supported languages (recursively). */
    fun findMissingTranslations(): List<String> {
        val issues = mutableListOf<String>()
        fun inspect(prefix: String, obj: Any) {
            obj::class.java.declaredFields
                .filter { !it.isSynthetic }
                .forEach { f ->
                    f.isAccessible = true
                    val v = f.get(obj)
                    if (f.type == String::class.java) {
                        if ((v as? String).isNullOrBlank()) {
                            issues.add("$prefix.${f.name}")
                        }
                    } else if (v != null && f.type.name.startsWith("com.example.ui.i18n.")) {
                        inspect("$prefix.${f.name}", v)
                    }
                }
        }
        listOf("EN" to english, "AM" to amharic, "OM" to afaanOromo).forEach { (code, data) ->
            inspect(code, data)
        }
        return issues
    }
}

